#!/usr/bin/env python3
"""Generate src/font6x9.inc and src/palette.inc.

Font: the public-domain X11 "misc-fixed" 6x9 glyphs (shipped as koi6x9 in the Cyrillic fixed-font
package). Printable ASCII only (32..126), 9 bytes per glyph, one byte per row, bit 7 = leftmost pixel.
Needs Pillow and a copy of koi6x9.pcf.gz (path given as argv[1], default: the Debian location).
"""
import gzip, io, sys
from PIL import PcfFontFile

src = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/X11/cyrillic/koi6x9.pcf.gz'
font = PcfFontFile.PcfFontFile(io.BytesIO(gzip.open(src).read()))

out = ['; Generated by tools/gen_assets.py - do not edit.',
       '; 6x9 bitmap font, ASCII 32..126, 9 bytes/glyph (X11 misc-fixed, public domain).', 'font:']
for c in range(32, 127):
    g = font.glyph[c - 1]            # PIL indexes this PCF's encoding table off by one
    im = g[3]
    rows = []
    for y in range(9):
        b = 0
        for x in range(6):
            if im.getpixel((x, y)):
                b |= 0x80 >> x
        rows.append(b)
    out.append('    .db ' + ','.join('0%02Xh' % r for r in rows) + '    ; ' + (repr(chr(c)) if c != 39 else "'\\''"))
open('src/font6x9.inc', 'w').write('\n'.join(out) + '\n')

# UI palette, entries 0..15 (entries 16..255 belong to the page's images). 1555: x RRRRR GGGGG BBBBB (as graphx does).
ui = [
    (16, 20, 28),     # 0 background
    (236, 236, 226),  # 1 text
    (140, 146, 156),  # 2 dim text
    (36, 66, 140),    # 3 bar background
    (255, 255, 255),  # 4 bar text
    (52, 64, 108),    # 5 selected block background
    (255, 208, 60),   # 6 accent / caret / selection marker
    (255, 96, 84),    # 7 error
    (110, 210, 150),  # 8 ok
    (80, 86, 96),     # 9 border
]
ui += [(0, 0, 0)] * (16 - len(ui))
w = ['; Generated by tools/gen_assets.py - do not edit.', 'uiPalette:']
for r, g, b in ui:
    v = ((r >> 3) << 10) | ((g >> 3) << 5) | (b >> 3)
    w.append('    .dw 0%04Xh    ; (%d,%d,%d)' % (v, r, g, b))
open('src/palette.inc', 'w').write('\n'.join(w) + '\n')
print('wrote src/font6x9.inc src/palette.inc')
